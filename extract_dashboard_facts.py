#!/usr/bin/env python3
"""
extract_dashboard_facts.py
============================
Решает конкретную проблему: DeepSeek (или другой ИИ) может "обновить"
дашборд за 10 секунд, просто поменяв даты в тексте, а не проведя реальный
поиск по каждому фактору. Проверить весь файл (1300+ строк) на глаз —
слишком долго. Этот скрипт вытаскивает только ключевые числа в короткий
список — 10-15 строк вместо всего файла.

КАК ИСПОЛЬЗОВАТЬ:
  1. После того как DeepSeek (или кто угодно) "обновил" dashboard.html,
     запустите: python3 extract_dashboard_facts.py dashboard.html
  2. Скопируйте вывод (короткий, займёт секунду прочитать)
  3. Пришлите этот короткий вывод Claude с просьбой "проверь, реальные
     ли это цифры" — это займёт у Claude 3-5 быстрых поисков вместо
     полного обновления файла, то есть в разы дешевле по токенам.
  4. Claude либо подтвердит, либо укажет на подозрительные несовпадения.

Использование:
    python3 extract_dashboard_facts.py dashboard.html
"""

import re
import sys


# Каждый паттерн ищет конкретный факт + короткий контекст вокруг него.
# При необходимости добавляйте новые факторы сюда же.
FACT_PATTERNS = [
    ("Дата последнего обновления", r'Последнее полное обновление дашборда:\s*<strong>([^<]+)</strong>'),
    ("Цена золота (в тексте, не live)", r'\$[\d,]+\.\d{2}'),
    ("Ставка ФРС (диапазон)", r'\d\.\d{2}[–\-]\d\.\d{2}%'),
    ("CPI", r'CPI[^.]{0,60}?(\d+\.\d+%)'),
    ("NFP / занятость", r'(?:NFP|занятост\w+)[^.]{0,80}?([+\-]?\d+K)'),
    ("PCE", r'PCE[^.]{0,60}?(\d+\.\d+%)'),
    ("Индекс доллара / DXY", r'(?:DXY|доллара?)[^.]{0,60}?(\d{2,3}\.\d)'),
    ("Доходность 10Y", r'10[YЛ][^.]{0,60}?(\d+\.\d+%)'),
    ("COT net long", r'(?:net long|чистая длинная)[^.]{0,60}?([\d,]+)'),
]


def extract_facts(path):
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()

    print(f"=== Факты, извлечённые из {path} ===\n")
    print("Скопируйте всё ниже и пришлите Claude с просьбой сверить с реальностью:\n")
    print("-" * 60)

    for label, pattern in FACT_PATTERNS:
        matches = re.findall(pattern, content, re.IGNORECASE)
        if matches:
            # Показываем первые 3 совпадения на случай, если факт встречается
            # в нескольких местах — так сразу видно, если они не совпадают
            unique = list(dict.fromkeys(matches))[:3]
            print(f"{label}: {', '.join(unique)}")
        else:
            print(f"{label}: (не найдено — возможно, формат в файле другой)")

    print("-" * 60)
    print("\n⚠️  Это не полная проверка — только сырые цифры. Claude всё равно")
    print("должен реально проверить их поиском, а не просто сказать 'выглядит правдоподобно'.")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Использование: python3 extract_dashboard_facts.py <путь_к_dashboard.html>")
        sys.exit(1)
    extract_facts(sys.argv[1])
